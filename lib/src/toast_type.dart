/// The type/variant of the toast notification.
enum ToastType {
  /// Green success toast. Use for successful operations.
  success,

  /// Red error toast. Use for failures or errors.
  error,

  /// Yellow warning toast. Use for warnings or cautions.
  warning,

  /// Blue info toast. Use for informational messages.
  info,

  /// Gray neutral toast. Use for general notifications.
  neutral,
}
